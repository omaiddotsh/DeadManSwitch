#!/usr/bin/env node
// Regenerates src/abi.ts from the Foundry artifact. Run via `npm run abi`
// after `forge build` in ../contracts. The test suite (test/abi.test.ts) fails
// when the checked-in ABI drifts from the artifact.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = resolve(here, "../../contracts/out/DeadManSwitch.sol/DeadManSwitch.json");
const outPath = resolve(here, "../src/abi.ts");

let artifact;
try {
  artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
} catch (err) {
  console.error(`cannot read ${artifactPath}: ${err.message}`);
  console.error("build the contract first: cd ../contracts && forge build");
  process.exit(1);
}
if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
  console.error(`${artifactPath} has no .abi array`);
  process.exit(1);
}

const body = JSON.stringify(artifact.abi, null, 2);
const src = `// GENERATED by \`npm run abi\` (tools/gen-abi.mjs) from
// contracts/out/DeadManSwitch.sol/DeadManSwitch.json. Do not edit by hand.
// test/abi.test.ts fails when this drifts from the artifact.

export const dmsAbi = ${body} as const;
`;
writeFileSync(outPath, src);
console.log(`wrote ${outPath} (${artifact.abi.length} entries)`);
