#!/usr/bin/env node
// Regenerate lib/abi.ts from the Foundry artifact.
//
//   cd contracts && forge build        # produces out/DeadManSwitch.sol/DeadManSwitch.json
//   cd frontend && npm run gen:abi
//
// The artifact directory is gitignored, so lib/abi.ts is the committed source of
// truth for the frontend. `npm run gen:abi -- --check` exits non-zero when the
// committed file is out of date.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/DeadManSwitch.sol/DeadManSwitch.json");
const target = resolve(here, "../lib/abi.ts");
const check = process.argv.includes("--check");

if (!existsSync(artifact)) {
  console.error(`missing ${artifact}\nrun: cd contracts && forge build`);
  process.exit(1);
}

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
if (!Array.isArray(abi) || abi.length === 0) {
  console.error(`no .abi in ${artifact}`);
  process.exit(1);
}

const out =
  "// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/out/DeadManSwitch.sol/DeadManSwitch.json.\n" +
  "// Do not edit by hand: change contracts/src/DeadManSwitch.sol, run `forge build`, then `npm run gen:abi`.\n\n" +
  `export const dmsAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;

if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("lib/abi.ts is out of date with the contract artifact; run `npm run gen:abi`");
    process.exit(1);
  }
  console.log("lib/abi.ts is up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${abi.length} entries)`);
}
